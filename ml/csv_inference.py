"""Offline CSV inference using the existing trained Random Forest.

No TomTom, OpenWeather, FastAPI or Render calls are made here.
Only load a trusted model artifact generated by this repository.
"""
from __future__ import annotations

from pathlib import Path
import sys

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from ml.random_forest_model import FEATURES, load_model

REQUIRED = [
    "timestamp_utc", "location_id", "current_speed_kmph",
    "free_flow_speed_kmph", "confidence", "temperature_c",
    "humidity_pct", "rain_1h_mm",
]
OPTIONAL = ["latitude", "longitude"]
MAX_ROWS = 25000


def prepare_uploaded_csv(source) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Return (valid model-ready rows, invalid rows with reasons)."""
    df = pd.read_csv(source)
    if df.empty:
        raise ValueError("CSV is empty.")
    if len(df) > MAX_ROWS:
        raise ValueError(f"Maximum {MAX_ROWS} rows per upload.")
    missing = sorted(set(REQUIRED) - set(df.columns))
    if missing:
        raise ValueError("Missing columns: " + ", ".join(missing))

    df = df.copy()
    df["source_row"] = range(2, len(df) + 2)
    df["timestamp_utc"] = pd.to_datetime(df["timestamp_utc"], utc=True, errors="coerce")
    df["location_id"] = df["location_id"].astype("string").str.strip()
    for col in REQUIRED[2:] + [c for c in OPTIONAL if c in df]:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    reasons = pd.Series("", index=df.index, dtype="string")
    def reject(mask, reason):
        nonlocal reasons
        reasons = reasons.mask(mask, reasons + reason + "; ")

    reject(df["timestamp_utc"].isna(), "invalid timestamp")
    reject(df["location_id"].isna() | df["location_id"].eq(""), "missing location_id")
    reject(df["current_speed_kmph"].isna() | (df["current_speed_kmph"] < 0), "invalid current speed")
    reject(df["free_flow_speed_kmph"].isna() | (df["free_flow_speed_kmph"] <= 0), "invalid free flow speed")
    reject(df["confidence"].notna() & ~df["confidence"].between(0, 1), "confidence outside 0..1")
    reject(df["humidity_pct"].notna() & ~df["humidity_pct"].between(0, 100), "humidity outside 0..100")
    reject(df["rain_1h_mm"].notna() & (df["rain_1h_mm"] < 0), "negative rainfall")
    for col, low, high in [("latitude", -90, 90), ("longitude", -180, 180)]:
        if col in df:
            reject(df[col].notna() & ~df[col].between(low, high), f"invalid {col}")
    invalid = df[reasons.ne("")].copy()
    invalid["error"] = reasons[reasons.ne("")]
    valid = df[reasons.eq("")].copy()
    if valid.empty:
        return valid, invalid

    local = valid["timestamp_utc"].dt.tz_convert("Asia/Kolkata")
    valid["current_speed"] = valid["current_speed_kmph"]
    valid["free_flow_speed"] = valid["free_flow_speed_kmph"]
    valid["speed_ratio"] = valid["current_speed"] / valid["free_flow_speed"]
    valid["traffic_confidence"] = valid["confidence"]
    valid["temperature"] = valid["temperature_c"]
    valid["humidity"] = valid["humidity_pct"]
    valid["rain_1h"] = valid["rain_1h_mm"]
    valid["hour"] = local.dt.hour
    valid["day_of_week"] = local.dt.dayofweek
    return valid, invalid


def predict_csv(source) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Predict congestion 15 minutes after each valid observation."""
    valid, invalid = prepare_uploaded_csv(source)
    if valid.empty:
        return pd.DataFrame(), invalid
    bundle = load_model()
    model = bundle["pipeline"]
    # The model's exact feature order is essential.
    if bundle["features"] != FEATURES:
        raise ValueError("Model feature schema mismatch.")
    labels = model.predict(valid[FEATURES])
    result = valid[["source_row", "timestamp_utc", "location_id",
                    "current_speed_kmph", "free_flow_speed_kmph"] +
                   [c for c in OPTIONAL if c in valid]].copy()
    result["prediction_at_utc"] = result["timestamp_utc"] + pd.Timedelta(minutes=15)
    result["predicted_congestion"] = labels
    if hasattr(model, "predict_proba"):
        result["model_probability"] = model.predict_proba(valid[FEATURES]).max(axis=1)
    result["mode"] = "historical_csv_offline"
    return result, invalid
